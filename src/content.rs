    #[test]
    fn recycling_rejects_every_faction_identity_the_target_does_not_have() {
        let (port, view) = recycle_port(vec![
            (
                "regions_tables",
                demo_table("regions_tables", &[("acadia", 1)]),
            ),
            (
                PERMISSION_TABLE,
                permission_table(&[("unit_a", "mughal"), ("unit_a", "britain")]),
            ),
        ]);
        let mut rules = recycle_rules();
        rules.factions["mughal"] = json!({"source": "etw"});
        rules.regions["acadia"]["owner"] = json!("mughal");
        rules.regions["acadia"]["rebel_faction"] = json!("united_states");
        rules.armies["mughal"] = json!([]);
        let problems = recycle_problems_in(&recycle_target(), &rules, &port, &view)
            .unwrap()
            .join("\n");
        for expected in [
            "faction mughal is not a target faction",
            "faction mughal is not defined by the target",
            "region acadia: owner",
            "region acadia: rebel_faction",
            "armies: mughal",
            "units_to_exclusive_faction_permissions_tables.faction would refer to faction(s) the target does not define: mughal",
        ] {
            assert!(
                problems.contains(expected),
                "missing {expected:?} in\n{problems}"
            );
        }
        assert!(!problems.contains("britain"), "{problems}");
    }

