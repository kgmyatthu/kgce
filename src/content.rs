struct Staged {
    version: u32,
    /// `(owner, row object)`
    items: Vec<(String, Value)>,
}

type StagedMap = BTreeMap<String, Staged>;

fn add_staged(staged: &mut StagedMap, owner: &str, doc: &Value, origin: &str) -> Result<()> {
    let obj = doc
        .as_object()
        .with_context(|| format!("{origin}: row file must be a JSON object"))?;
    let keys: BTreeSet<&str> = obj.keys().map(String::as_str).collect();
    if keys != BTreeSet::from(["rows", "table", "version"]) {
        bail!("{origin}: expected exactly the keys table/version/rows, found {keys:?}");
    }
    let table = obj["table"]
        .as_str()
        .with_context(|| format!("{origin}: `table` must be a string"))?;
    if !table.ends_with("_tables") {
        bail!("{origin}: table name {table} must end with _tables");
    }
    let version = obj["version"]
        .as_u64()
        .and_then(|v| u32::try_from(v).ok())
        .with_context(|| format!("{origin}: `version` must be a non-negative integer"))?;
    let rows = obj["rows"]
        .as_array()
        .with_context(|| format!("{origin}: `rows` must be an array"))?;
    let entry = staged.entry(table.to_owned()).or_insert_with(|| Staged {
        version,
        items: Vec::new(),
    });
    if entry.version != version {
        bail!(
            "{origin}: {table} version {version} differs from {} staged by another owner",
            entry.version
        );
    }
    entry
        .items
        .extend(rows.iter().map(|r| (owner.to_owned(), r.clone())));
    Ok(())
}

fn sorted_files(dir: &Path, extension: &str) -> Result<Vec<PathBuf>> {
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .with_context(|| format!("Read {}", dir.display()))?
        .map(|e| e.map(|e| e.path()))
        .collect::<std::io::Result<Vec<PathBuf>>>()
        .with_context(|| format!("List {}", dir.display()))?;
    files.retain(|p| p.is_file() && p.extension().and_then(|e| e.to_str()) == Some(extension));
    files.sort();
    Ok(files)
}

fn owner_of(path: &Path, separator: Option<&str>) -> Result<String> {
    let stem = path
        .file_stem()
        .and_then(|s| s.to_str())
        .with_context(|| format!("Bad file name {}", path.display()))?;
    match separator {
        Some(sep) => stem
            .split_once(sep)
            .map(|(o, _)| o.to_owned())
            .ok_or_else(|| anyhow!("{} must be named <owner>{sep}<table>.json", path.display())),
        None => Ok(stem.to_owned()),
    }
}

/// Where the six map tables come from: the real map builder output, or the curated copy of the accepted
/// conversion (used for analysis, which must not run the terrain build).
#[derive(Clone, Copy)]
pub enum MapRows<'a> {
    Artifacts(&'a MapArtifacts),
    Curated,
}

/// A campaign region the project adds to the ETW world: an activated wilderness region (`source` is its donor) or a
/// region split (`source` is the region it is cut from). The rows of both are derived the same way.
#[derive(Clone, Debug)]
pub struct ExtraRegion {
    pub key: String,
    /// playable / split-from region whose `regions_tables` row serves as the template
    pub source: String,
    pub name: String,
    pub settlement_key: String,
    pub settlement_name: String,
    pub colour: [u8; 3],
}

/// The activated and split regions of `project` in the order they apply: activations first (a split may cut an
/// activated region, so its source row must exist by then), then splits.
pub fn extra_regions(project: &Project) -> Vec<ExtraRegion> {
    let activations = project.activations.iter().map(|a| ExtraRegion {
        key: a.key.clone(),
        source: a.donor.clone(),
        name: a.name.clone(),
        settlement_key: a.settlement_key(),
        settlement_name: a.settlement_name.clone(),
        colour: a.colour,
    });
    let splits = project.splits.iter().map(|s| ExtraRegion {
        key: s.key.clone(),
        source: s.source.clone(),
        name: s.name.clone(),
        settlement_key: s.settlement_key(),
        settlement_name: s.settlement_name.clone(),
        colour: s.colour,
    });
    activations.chain(splits).collect()
}

/// The `regions_tables` row of an extra region is its source's row with the region's key, continent (from the rules),
/// colour and battle name (the capital settlement's name, as for every region). Extra regions apply in order, so a source may be the key of an earlier one.
fn derive_extra_rows(staged: &mut StagedMap, rules: &Rules, extra: &[ExtraRegion]) -> Result<()> {
    if extra.is_empty() {
        return Ok(());
    }
    let regions = object(&rules.regions, "regions")?;
    let entry = staged
        .get_mut("regions_tables")
        .context("curated regions_tables rows are missing: the rows of the split regions cannot be derived")?;
    for region in extra {
        let existing = entry
            .items
            .iter()
            .position(|(_, r)| r.get("key").and_then(Value::as_str) == Some(region.key.as_str()));
        // a region the shipped table already lists (e.g. `indochina`, a backdrop region of the Napoleon map) is
        // replaced in place, keeping the row's position; any other key is cloned from its source row
        let (owner, mut row) = match existing {
            Some(at) => entry.items[at].clone(),
            None => entry
                .items
                .iter()
                .find(|(_, r)| r.get("key").and_then(Value::as_str) == Some(region.source.as_str()))
                .cloned()
                .with_context(|| format!("region {}: source region {} has no regions_tables row", region.key, region.source))?,
        };
        let rule = regions
            .get(&region.key)
            .with_context(|| format!("region {}: the region rules have no entry for it", region.key))?;
        row["key"] = Value::from(region.key.clone());
        if let Some(continent) = rule.get("continent").and_then(Value::as_str) {
            row["continent"] = Value::from(continent);
        }
        row["r"] = Value::from(region.colour[0]);
        row["g"] = Value::from(region.colour[1]);
        row["b"] = Value::from(region.colour[2]);
        row["battle_name"] = Value::from(region.settlement_name.clone());
        match existing {
            Some(at) => entry.items[at] = (owner, row),
            None => entry.items.push((owner, row)),
        }
    }
    Ok(())
}

fn stage_rows(rules: &Rules, extra: &[ExtraRegion], map: MapRows<'_>) -> Result<StagedMap> {
    let curated_map = matches!(map, MapRows::Curated);
    let mut staged = StagedMap::new();
    for path in sorted_files(&rules.root.join("db_rows"), "json")? {
        let owner = owner_of(&path, Some("__"))?;
        if owner == MAP_OWNER && !curated_map {
            // Map rows are regenerated from the ETW originals by the map builder; the curated copy is not used.
            continue;
        }
        let doc: Value = serde_json::from_slice(
            &fs::read(&path).with_context(|| format!("Read {}", path.display()))?,
        )
        .with_context(|| format!("Parse {}", path.display()))?;
        add_staged(&mut staged, &owner, &doc, &path.display().to_string())?;
    }
    derive_extra_rows(&mut staged, rules, extra)?;
    for (table, st) in &staged {
        let is_map = MAP_TABLES.contains(&table.as_str());
        if is_map && st.items.iter().any(|(owner, _)| owner != MAP_OWNER) {
            bail!(
                "curated rows provide map-owned table {table}; map tables must come from the map builder"
            );
        }
        if !is_map && !SEED_TABLES.contains(&table.as_str()) {
            bail!("curated rows provide unexpected table {table}");
        }
        if st.items.is_empty() {
            bail!("curated table {table} has no rows");
        }
    }
    let mut provided = BTreeSet::new();
    match map {
        MapRows::Artifacts(map) => {
            for (name, doc) in &map.db_rows {
                let table = db::normalize_table_name(name);
                if doc.get("table").and_then(Value::as_str) != Some(table.as_str()) {
                    bail!("map artifact {name}: embedded table name does not match its key");
                }
                if !MAP_TABLES.contains(&table.as_str()) {
                    bail!("map artifacts contain unexpected table {table}");
                }
                add_staged(
                    &mut staged,
                    MAP_OWNER,
                    doc,
                    &format!("map artifact {table}"),
                )?;
                provided.insert(table);
            }
        }
        MapRows::Curated => provided.extend(
            MAP_TABLES
                .iter()
                .filter(|t| staged.contains_key(**t))
                .map(|t| (*t).to_owned()),
        ),
    }
    let missing: Vec<&str> = MAP_TABLES
        .iter()
        .copied()
        .filter(|t| !provided.contains(*t))
        .collect();
    if !missing.is_empty() {
        bail!("map builder did not provide tables {missing:?}");
    }
    if let Some(empty) = MAP_TABLES.iter().find(|t| staged[**t].items.is_empty()) {
        bail!("map builder produced no rows for {empty}");
    }
    let missing: Vec<&str> = SEED_TABLES
        .iter()
        .copied()
        .filter(|t| !staged.contains_key(*t))
        .collect();
    if !missing.is_empty() {
        bail!("curated database rows are missing for tables {missing:?}");
    }
    Ok(staged)
}

fn object<'a>(v: &'a Value, what: &str) -> Result<&'a Map<String, Value>> {
    v.as_object()
        .with_context(|| format!("rules {what} must be a JSON object"))
}

/// Every faction of the rules must already be a faction of the target: no faction identity is ever generated, so
/// no faction-owned table (factions, uniforms, names, technologies, ...) is staged.
fn ensure_target_factions(rules: &Rules) -> Result<()> {
    let foreign: Vec<&str> = object(&rules.factions, "factions")?
        .iter()
        .filter(|(_, info)| info.get("source").and_then(Value::as_str) != Some("ntw"))
        .map(|(k, _)| k.as_str())
        .collect();
    if !foreign.is_empty() {
        bail!(
            "the resolved rules still contain factions that are not target factions: {foreign:?}"
        );
    }
    Ok(())
}

/// Definition of the permission table: the target's version when it is known, else the newest schema version.
fn permission_definition(schema: &db::Schema, version: Option<u32>) -> Result<&db::Definition> {
    let found = match version {
        Some(v) => schema.definition(PERMISSION_TABLE, i64::from(v)),
        None => schema
            .definitions(PERMISSION_TABLE)
            .iter()
            .max_by_key(|d| d.version),
    };
    let def = found.with_context(|| {
        format!("schema_nap.ron has no definition of {PERMISSION_TABLE} (version {version:?})")
    })?;
    if def.fields.len() != 3 {
        bail!(
            "{PERMISSION_TABLE} has {} columns, expected unit/faction/allowed",
            def.fields.len()
        );
    }
    Ok(def)
}

/// Permission rows for the start armies: a unit exclusive to other factions needs an explicit permission for the
/// faction that fields it. The target's permission table is only read when some army has units.
fn derive_permissions(staged: &mut StagedMap, snapshot: &Snapshot, rules: &Rules) -> Result<()> {
    ensure_target_factions(rules)?;
    let armies = object(&rules.armies, "armies")?;
    let needs_target = armies.values().any(|list| {
        list.as_array().is_some_and(|list| {
            list.iter().any(|army| {
                army.get("units")
                    .and_then(Value::as_array)
                    .is_some_and(|units| !units.is_empty())
            })
        })
    });
    let target = if needs_target {
        Some(db::load_campaign_table(
            snapshot,
            rules,
            db::CampaignTable::UnitPermissions,
        )?)
    } else {
        None
    };
    let schema = db::schema(rules, Game::Ntw)?;
    let def = permission_definition(&schema, target.as_ref().map(|t| t.version))?;
    let names: Vec<String> = def.fields.iter().map(|f| f.name.clone()).collect();
    let mut exclusive: HashMap<&str, HashSet<&str>> = HashMap::new();
    for r in target.iter().flat_map(|t| t.rows.iter()) {
        match (r.first(), r.get(1), r.get(2)) {
            (Some(Cell::Str(unit)), Some(Cell::Str(faction)), Some(Cell::Bool(allowed))) => {
                if *allowed {
                    exclusive
                        .entry(unit.as_str())
                        .or_default()
                        .insert(faction.as_str());
                }
            }
            other => {
                bail!("{PERMISSION_TABLE}: unexpected row layout {other:?}")
            }
        }
    }
    let mut items: Vec<(String, Value)> = Vec::new();
    let mut seen: HashSet<(String, String)> = HashSet::new();
    for (faction, list) in armies {
        let list = list
            .as_array()
            .with_context(|| format!("rules armies.{faction} must be an array"))?;
        for army in list {
            let units = army
                .get("units")
                .and_then(Value::as_array)
                .with_context(|| format!("rules armies.{faction}: army without units"))?;
            for unit in units {
                let unit = unit.as_str().with_context(|| {
                    format!("rules armies.{faction}: unit names must be strings")
                })?;
                if exclusive
                    .get(unit)
                    .is_some_and(|allowed| !allowed.contains(faction.as_str()))
                    && seen.insert((unit.to_owned(), faction.clone()))
                {
                    let mut row = Map::new();
                    row.insert(names[0].clone(), Value::String(unit.to_owned()));
                    row.insert(names[1].clone(), Value::String(faction.clone()));
                    row.insert(names[2].clone(), Value::Bool(true));
                    items.push(("rules".to_owned(), Value::Object(row)));
                }
            }
        }
    }
    staged.insert(
        PERMISSION_TABLE.to_owned(),
        Staged {
            version: u32::try_from(def.version).with_context(|| {
                format!("{PERMISSION_TABLE}: bad schema version {}", def.version)
            })?,
            items,
        },
    );
    Ok(())
}

