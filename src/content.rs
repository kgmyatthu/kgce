//! Native content slice: the 10 additive `nap_world` database tables of the world campaign and the two full merged `.loc` files.
//!
//! Inputs
//!  * curated policy assets in `rules.root`: `db_rows/<owner>__<table>.json` (additive rows of the accepted
//!    conversion), `loc/<owner>.tsv`, `schema_nap.ron` / `schema_emp.ron`;
//!  * the untouched ETW/NTW source snapshot (vanilla tables, `.loc` files);
//!  * the map owner's regenerated rows (`MapArtifacts.db_rows` / `loc_rows`), which are authoritative for the six
//!    map tables and the map strings, and the (project-adjusted) `Rules`.
//!
//! The world campaign only ever uses existing target factions (no faction identity is generated): the permission rows
//! for factions that field units in their start armies follow `Rules.armies`.
//! Everything is cross-checked (schema version, additive keys, key collisions, every schema/curated foreign key,
//! every faction/region/unit/building referenced by the rules, localisation coverage) and any failure aborts the
//! build with the offending rows listed.

