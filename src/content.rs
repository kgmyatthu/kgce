fn row_identity(row: &[Cell], cols: &[usize]) -> String {
    cols.iter()
        .map(|&c| row[c].key())
        .collect::<Vec<_>>()
        .join("\u{1f}")
}

/// Port rows of one table (typed), parallel to `owners`.
#[derive(Clone, Debug)]
pub struct PortTable {
    pub table: Table,
    pub owners: Vec<String>,
    /// Column names that identify a row (the content identity; never silently different from vanilla).
    pub identity: Vec<String>,
    ident_cols: Vec<usize>,
}

impl PortTable {
    /// A port table over an already typed table; its identity is the policy/key/whole-row identity of the table.
    pub fn from_table(table: Table, owner: &str) -> Result<Self> {
        let identity = identity_columns(&table.name, &table.fields);
        let ident_cols = identity
            .iter()
            .map(|n| table.column(n))
            .collect::<Result<Vec<usize>>>()?;
        Ok(Self {
            owners: vec![owner.to_owned(); table.rows.len()],
            table,
            identity,
            ident_cols,
        })
    }

    pub fn identity_of(&self, row: &[Cell]) -> String {
        row_identity(row, &self.ident_cols)
    }

    /// Removes the rows with the given identities; returns how many were removed.
    pub fn drop_identities(&mut self, ids: &BTreeSet<String>) -> usize {
        let before = self.table.rows.len();
        let mut keep = Vec::with_capacity(before);
        for row in &self.table.rows {
            keep.push(!ids.contains(&row_identity(row, &self.ident_cols)));
        }
        let mut index = 0;
        self.table.rows.retain(|_| {
            index += 1;
            keep[index - 1]
        });
        index = 0;
        self.owners.retain(|_| {
            index += 1;
            keep[index - 1]
        });
        before - self.table.rows.len()
    }
}

/// Modified tables need a declared row identity; whole-row comparison cannot detect
/// conflicting values for the same key when schema key metadata is absent.
pub(crate) fn has_row_identity(table: &str, fields: &[db::Field]) -> bool {
    IDENTITY.iter().any(|(name, _)| *name == table) || fields.iter().any(|field| field.is_key)
}

/// Content identity columns of a table: the policy override, else the schema key columns, else every column.
pub fn identity_columns(table: &str, fields: &[db::Field]) -> Vec<String> {
    match IDENTITY.iter().find(|(n, _)| *n == table) {
        Some((_, cols)) => cols.iter().map(|c| (*c).to_owned()).collect(),
        None => {
            let keys: Vec<String> = fields
                .iter()
                .filter(|f| f.is_key)
                .map(|f| f.name.clone())
                .collect();
            if keys.is_empty() {
                fields.iter().map(|f| f.name.clone()).collect()
            } else {
                keys
            }
        }
    }
}

/// Identity of `row` over the named columns of `fields`.
pub fn identity_of_row(fields: &[db::Field], names: &[String], row: &[Cell]) -> Option<String> {
    let cols: Option<Vec<usize>> = names
        .iter()
        .map(|n| fields.iter().position(|f| &f.name == n))
        .collect();
    cols.map(|c| row_identity(row, &c))
}

/// Seed rows adapted to the rules and typed against the NTW schema.
#[derive(Clone, Debug)]
pub struct Port {
    pub tables: BTreeMap<String, PortTable>,
}

impl Port {
    /// Generated tables plus the given target rows (which replace dropped port rows).
    pub fn view(&self, target_rows: &BTreeMap<String, Vec<Vec<Cell>>>) -> View {
        let mut view = View::default();
        for (name, pt) in &self.tables {
            let mut table = pt.table.clone();
            if let Some(rows) = target_rows.get(name) {
                let ids = view.reused.entry(name.clone()).or_default();
                for row in rows {
                    if row.len() == table.fields.len() {
                        ids.insert(pt.identity_of(row));
                        table.rows.push(row.clone());
                    }
                }
            }
            view.tables.insert(name.clone(), table);
        }
        view
    }
}

/// Types every staged table against the NTW schema (its version is the staged one).
fn type_staged(rules: &Rules, staged: &StagedMap) -> Result<BTreeMap<String, PortTable>> {
    let expected: BTreeSet<String> = port_table_names().into_iter().collect();
    let have: BTreeSet<String> = staged.keys().cloned().collect();
    if have != expected {
        bail!("generated table set {have:?} differs from the expected {expected:?}");
    }
    let schema = db::schema(rules, Game::Ntw)?;
    let mut tables = BTreeMap::new();
    for (tname, st) in staged {
        let def = schema
            .definition(tname, i64::from(st.version))
            .with_context(|| {
                format!(
                    "schema_nap.ron has no definition of {tname} version {}",
                    st.version
                )
            })?;
        let rows: Vec<Value> = st.items.iter().map(|(_, r)| r.clone()).collect();
        let table = Table::from_json_rows(tname, st.version, &def.fields, &rows)
            .with_context(|| format!("Convert {tname} rows"))?;
        let identity = identity_columns(tname, &table.fields);
        let ident_cols = identity
            .iter()
            .map(|n| table.column(n))
            .collect::<Result<Vec<usize>>>()?;
        tables.insert(
            tname.clone(),
            PortTable {
                table,
                owners: st.items.iter().map(|(o, _)| o.clone()).collect(),
                identity,
                ident_cols,
            },
        );
    }
    Ok(tables)
}

/// Stages the curated, map and rule-derived rows and types them. Exactly the tables of [`port_table_names`] exist.
pub fn stage_port(snapshot: &Snapshot, rules: &Rules, extra: &[ExtraRegion], map: MapRows<'_>) -> Result<Port> {
    let mut staged = stage_rows(rules, extra, map)?;
    derive_permissions(&mut staged, snapshot, rules)?;
    Ok(Port {
        tables: type_staged(rules, &staged)?,
    })
}

/// The curated rows of the generated tables, typed against the NTW schema without any target database: the
/// seed tables, the curated copy of the six map tables and an empty permission table (its rows only exist once the
/// start armies are checked against the target). Used to discover the tables the generated rows reference.
pub fn requirement_rows(rules: &Rules) -> Result<BTreeMap<String, Table>> {
    let mut staged = stage_rows(rules, &[], MapRows::Curated)?;
    let schema = db::schema(rules, Game::Ntw)?;
    let def = permission_definition(&schema, None)?;
    staged.insert(
        PERMISSION_TABLE.to_owned(),
        Staged {
            version: u32::try_from(def.version).with_context(|| {
                format!("{PERMISSION_TABLE}: bad schema version {}", def.version)
            })?,
            items: Vec::new(),
        },
    );
    Ok(type_staged(rules, &staged)?
        .into_iter()
        .map(|(name, pt)| (name, pt.table))
        .collect())
}

/// The port rows must be additive: same table version as the target table, no row colliding with a target
/// row, no duplicate key or identical row inside the port.
pub fn check_port(port: &Port, snapshot: &Snapshot, rules: &Rules) -> Result<()> {
    for (tname, pt) in &port.tables {
        let table = &pt.table;
        // Nothing is emitted for an empty table: neither its target table nor its version is consulted.
        if table.rows.is_empty() {
            continue;
        }
        let target = db::load_table_opt(snapshot, Game::Ntw, rules, tname)?;
        if let Some(v) = &target {
            if v.version != table.version {
                bail!(
                    "{tname}: generated rows use version {} but the target table is version {}",
                    table.version,
                    v.version
                );
            }
        }
        let key_cols: Vec<usize> = table
            .fields
            .iter()
            .enumerate()
            .filter(|(_, f)| f.is_key)
            .map(|(i, _)| i)
            .collect();
        let target_ids: HashSet<String> = match &target {
            Some(v) => {
                let cols = pt
                    .identity
                    .iter()
                    .map(|n| v.column(n))
                    .collect::<Result<Vec<usize>>>()?;
                v.rows.iter().map(|r| row_identity(r, &cols)).collect()
            }
            None => HashSet::new(),
        };
        let mut whole: HashMap<String, &str> = HashMap::new();
        let mut keys: HashMap<String, &str> = HashMap::new();
        for (row, owner) in table.rows.iter().zip(&pt.owners) {
            let id = pt.identity_of(row);
            if target_ids.contains(&id) {
                bail!(
                    "{tname} ({owner}): row {id:?} collides with a target row; generated rows must be additive"
                );
            }
            let sig = row.iter().map(Cell::key).collect::<Vec<_>>().join("\u{1f}");
            if let Some(first) = whole.insert(sig, owner.as_str()) {
                bail!("{tname}: identical row staged twice ({first} and {owner}): {id:?}");
            }
            if !key_cols.is_empty() {
                let k = row_identity(row, &key_cols);
                if let Some(first) = keys.insert(k.clone(), owner.as_str()) {
                    bail!("{tname}: duplicate key {k:?} ({first} and {owner})");
                }
            }
        }
    }
    Ok(())
}

/// Encodes every port table that still has rows as `db\<table>\nap_world`; returns the members and the row
/// count. Each encoding must survive a decode/encode cycle.
pub fn encode_port(port: &Port, rules: &Rules) -> Result<(BTreeMap<String, Vec<u8>>, usize)> {
    let schema = db::schema(rules, Game::Ntw)?;
    let mut members = BTreeMap::new();
    let mut total_rows = 0;
    for (name, pt) in &port.tables {
        let table = &pt.table;
        if table.rows.is_empty() {
            continue;
        }
        let bytes = db::encode(table).with_context(|| format!("Encode {name}"))?;
        let back =
            db::decode(name, &bytes, &schema).with_context(|| format!("Re-decode {name}"))?;
        if back.rows != table.rows || back.version != table.version || db::encode(&back)? != bytes {
            bail!("{name}: encoded table does not survive a decode/encode cycle");
        }
        total_rows += table.rows.len();
        members.insert(format!("db\\{name}\\{TABLE_FILE}"), bytes);
    }
    Ok((members, total_rows))
}

fn index_of(t: &Table, column: &str) -> Result<HashMap<String, usize>> {
    let col = t.column(column)?;
    let mut out = HashMap::with_capacity(t.rows.len());
    for (i, r) in t.rows.iter().enumerate() {
        out.insert(r[col].key(), i);
    }
    Ok(out)
}

fn value_set(t: &Table, column: usize) -> HashSet<String> {
    t.rows.iter().map(|r| r[column].key()).collect()
}

/// A campaign table of the view/port; target faction identities are read from the installed target, never staged here.
fn generated<'a>(tables: &'a BTreeMap<String, Table>, name: &str) -> Result<&'a Table> {
    tables
        .get(name)
        .with_context(|| format!("generated table {name} is missing"))
}

