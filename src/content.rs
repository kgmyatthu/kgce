#[derive(Clone, Debug, PartialEq)]
struct LocRow {
    text: String,
    tip: u8,
    owner: String,
}

type LocSets = [BTreeMap<String, LocRow>; 2];

fn loc_target(name: &str) -> Result<usize> {
    LOC_FILES
        .iter()
        .position(|(n, _)| *n == name)
        .ok_or_else(|| {
            anyhow!("unknown localisation target `{name}` (expected ui or localisation)")
        })
}

/// `key<TAB>text<TAB>tooltip[<TAB>ui|localisation]`
fn parse_tsv(text: &str, origin: &str) -> Result<Vec<(String, String, u8, String)>> {
    let mut out = Vec::new();
    for (n, line) in text.split('\n').enumerate() {
        let line = line.strip_suffix('\r').unwrap_or(line);
        if line.trim().is_empty() {
            continue;
        }
        let parts: Vec<&str> = line.split('\t').collect();
        if parts.len() < 3 || parts.len() > 4 {
            bail!(
                "{origin}:{}: expected 3-4 tab-separated columns, found {}",
                n + 1,
                parts.len()
            );
        }
        if parts[0].is_empty() {
            bail!("{origin}:{}: empty key", n + 1);
        }
        let tip: u8 = parts[2]
            .trim()
            .parse()
            .with_context(|| format!("{origin}:{}: tooltip flag must be 0-255", n + 1))?;
        let target = parts.get(3).copied().unwrap_or("localisation");
        loc_target(target).with_context(|| format!("{origin}:{}", n + 1))?;
        out.push((
            parts[0].to_owned(),
            parts[1].to_owned(),
            tip,
            target.to_owned(),
        ));
    }
    Ok(out)
}

fn add_loc(
    sets: &mut LocSets,
    owner: &str,
    key: String,
    text: String,
    tip: u8,
    target: &str,
) -> Result<()> {
    let idx = loc_target(target)?;
    if let Some(other) = sets
        .iter()
        .enumerate()
        .find(|(i, s)| *i != idx && s.contains_key(&key))
        .map(|(i, _)| i)
    {
        bail!(
            "localisation key {key} is staged for both {} and {}",
            LOC_FILES[other].0,
            LOC_FILES[idx].0
        );
    }
    let row = LocRow {
        text,
        tip,
        owner: owner.to_owned(),
    };
    match sets[idx].get(&key) {
        Some(existing) if existing.text != row.text || existing.tip != row.tip => {
            bail!(
                "localisation key {key} is staged twice with different content ({} vs {owner}): {:?} / {:?}",
                existing.owner,
                existing.text,
                row.text
            );
        }
        Some(_) => {}
        None => {
            sets[idx].insert(key, row);
        }
    }
    Ok(())
}

/// Owner-tagged strings staged for `text\ui.loc` / `text\localisation.loc`.
#[derive(Clone, Debug)]
pub struct LocPlan {
    sets: LocSets,
}

impl LocPlan {
    /// `(key, text, tooltip, target file index)` of every staged string.
    pub fn rows(&self) -> impl Iterator<Item = (&str, &str, u8, usize)> + '_ {
        self.sets.iter().enumerate().flat_map(|(i, set)| {
            set.iter()
                .map(move |(k, r)| (k.as_str(), r.text.as_str(), r.tip, i))
        })
    }

    pub fn is_empty(&self) -> bool {
        self.sets.iter().all(BTreeMap::is_empty)
    }

    pub fn contains(&self, key: &str) -> bool {
        self.sets.iter().any(|s| s.contains_key(key))
    }
}

/// Canonical (`/`, lower-case) effective path of a main LOC file.
pub fn loc_main_paths() -> [String; 2] {
    [
        LOC_FILES[0].1.replace('\\', "/"),
        LOC_FILES[1].1.replace('\\', "/"),
    ]
}

/// Collects the strings of the conversion: the curated strings of regions, map and campaign front end plus, when
/// the map builder ran, its localisation rows.
pub fn collect_loc(rules: &Rules, extra: &[ExtraRegion], map: MapRows<'_>) -> Result<LocPlan> {
    let mut sets: LocSets = [BTreeMap::new(), BTreeMap::new()];
    // An activated region the shipped strings already name (e.g. `indochina` -> "Burma") takes the project's names:
    // every source of that string is staged with the same, project-chosen text.
    let names: BTreeMap<String, String> = extra
        .iter()
        .flat_map(|region| {
            [
                (format!("regions_onscreen_{}", region.key), region.name.clone()),
                (format!("regions_battle_name_{}", region.key), region.settlement_name.clone()),
                (
                    format!("start_pos_settlements_onscreen_name_{}", region.settlement_key),
                    region.settlement_name.clone(),
                ),
            ]
        })
        .collect();
    for path in sorted_files(&rules.root.join("loc"), "tsv")? {
        let owner = owner_of(&path, None)?;
        if owner == MAP_OWNER && !matches!(map, MapRows::Curated) {
            continue;
        }
        let text = fs::read_to_string(&path).with_context(|| format!("Read {}", path.display()))?;
        for (key, text, tip, target) in parse_tsv(&text, &path.display().to_string())? {
            let text = names.get(&key).cloned().unwrap_or(text);
            add_loc(&mut sets, &owner, key, text, tip, &target)
                .with_context(|| path.display().to_string())?;
        }
    }
    // Activated and split regions: the rebel faction name is a rule-derived string. In analysis mode (no map builder
    // output) the region and settlement names are staged here as well; with map artifacts the map builder owns them.
    for region in extra {
        let rule = object(&rules.regions, "regions")?
            .get(&region.key)
            .with_context(|| format!("region {}: the region rules have no entry for it", region.key))?;
        let rebel = rule
            .get("rebel_name")
            .and_then(Value::as_str)
            .filter(|s| !s.is_empty())
            .with_context(|| format!("region {}: the region rules have no rebel_name", region.key))?;
        let mut rows = vec![(
            format!("start_pos_regions_rebel_faction_name_{}wld_napoleon", region.key),
            rebel.to_owned(),
        )];
        if matches!(map, MapRows::Curated) {
            rows.extend([
                (format!("regions_onscreen_{}", region.key), region.name.clone()),
                (format!("regions_battle_name_{}", region.key), region.settlement_name.clone()),
                (
                    format!("start_pos_settlements_onscreen_name_{}", region.settlement_key),
                    region.settlement_name.clone(),
                ),
            ]);
        }
        for (key, text) in rows {
            if text.contains(['\t', '\n']) {
                bail!("region {}: names must not contain tabs or line breaks", region.key);
            }
            add_loc(&mut sets, "content", key.clone(), names.get(&key).cloned().unwrap_or(text), 0, "localisation")?;
        }
    }
    if let MapRows::Artifacts(map) = map {
        if map.loc_rows.is_empty() {
            bail!("map builder provided no localisation rows");
        }
        for (key, text, tip, target) in &map.loc_rows {
            if key.is_empty() || key.contains(['\t', '\n']) || text.contains(['\t', '\n']) {
                bail!("map localisation row {key:?} contains a tab/newline or an empty key");
            }
            add_loc(
                &mut sets,
                MAP_OWNER,
                key.clone(),
                names.get(key).cloned().unwrap_or_else(|| text.clone()),
                *tip,
                target,
            )
            .context("map localisation rows")?;
        }
    }
    Ok(LocPlan { sets })
}

struct MergedLoc {
    bytes: Vec<u8>,
    keys: HashSet<String>,
    added: usize,
    replaced: usize,
}

/// Full file = vanilla entries (new text replacing an existing key in place) + new keys sorted by key.
fn merge_loc(base: &[u8], new: &BTreeMap<String, LocRow>) -> Result<MergedLoc> {
    let (version, mut merged) = db::decode_loc(base).context("Decode vanilla LOC")?;
    let mut index: HashMap<String, usize> = HashMap::with_capacity(merged.len());
    for (i, (k, _, _)) in merged.iter().enumerate() {
        index.insert(k.clone(), i);
    }
    let (mut added, mut replaced) = (0, 0);
    for (key, row) in new {
        match index.get(key) {
            Some(&i) => {
                merged[i] = (key.clone(), row.text.clone(), row.tip);
                replaced += 1;
            }
            None => {
                merged.push((key.clone(), row.text.clone(), row.tip));
                added += 1;
            }
        }
    }
    let mut keys = HashSet::with_capacity(merged.len());
    for (k, _, _) in &merged {
        if !keys.insert(k.clone()) {
            bail!("merged LOC would contain duplicate key {k}");
        }
    }
    let bytes = db::encode_loc(&merged, version)?;
    let (v2, again) = db::decode_loc(&bytes)?;
    if v2 != version || again != merged {
        bail!("merged LOC does not survive re-decoding");
    }
    Ok(MergedLoc {
        bytes,
        keys,
        added,
        replaced,
    })
}

/// Removes entries with the given keys from a LOC file, keeping order and version.
pub fn strip_loc_keys(bytes: &[u8], keys: &BTreeSet<String>) -> Result<Vec<u8>> {
    let (version, entries) = db::decode_loc(bytes)?;
    let kept: Vec<_> = entries
        .into_iter()
        .filter(|(k, _, _)| !keys.contains(k))
        .collect();
    db::encode_loc(&kept, version)
}

/// A port string whose key already exists in a target LOC member with different text.
#[derive(Clone, Debug)]
pub struct LocConflict {
    /// Canonical effective path of the target member that holds the string.
    pub member: String,
    pub key: String,
    pub target: (String, u8),
    pub port: (String, u8),
    /// Index (0 = ui, 1 = localisation) of the port file the string is staged for.
    pub port_file: usize,
}

/// Effective `.loc` members below `text/` as `(canonical path, key -> (text, tooltip))`.
pub fn effective_loc_members(
    snapshot: &Snapshot,
) -> Result<Vec<(String, BTreeMap<String, (String, u8)>)>> {
    let mut out = Vec::new();
    for name in snapshot.names(Game::Ntw, "text/") {
        if !name.ends_with(".loc") {
            continue;
        }
        let bytes = db::read_member(snapshot, Game::Ntw, &name)?;
        let parsed = db::parse_loc(&bytes).with_context(|| format!("Decode target {name}"))?;
        out.push((name, parsed));
    }
    Ok(out)
}

/// Port strings that would silently override or duplicate target text. With an English reference a target string
/// equal to the vanilla one is a plain vanilla replacement (the baseline conversion behaviour), not a conflict.
/// With a non-English reference (`base_english` false) the port's English text must never replace the native text
/// silently, so even vanilla-equal strings are reported.
pub fn loc_conflicts(
    plan: &LocPlan,
    snapshot: &Snapshot,
    base: &Snapshot,
    base_english: bool,
) -> Result<Vec<LocConflict>> {
    let members = effective_loc_members(snapshot)?;
    let mut vanilla: HashMap<String, (String, u8)> = HashMap::new();
    for (_, member) in LOC_FILES {
        vanilla.extend(db::parse_loc(&db::read_member(base, Game::Ntw, member)?)?);
    }
    let mut out = Vec::new();
    for (key, text, tip, file) in plan.rows() {
        for (path, entries) in &members {
            let Some(have) = entries.get(key) else {
                continue;
            };
            if have.0 == text && have.1 == tip {
                continue;
            }
            if base_english && vanilla.get(key) == Some(have) {
                continue;
            }
            out.push(LocConflict {
                member: path.clone(),
                key: key.to_owned(),
                target: have.clone(),
                port: (text.to_owned(), tip),
                port_file: file,
            });
        }
    }
    Ok(out)
}

struct LocMerge {
    /// Pack member name (backslashes) -> bytes: the two full LOC files and any rewritten extra member.
    members: BTreeMap<String, Vec<u8>>,
    keys: [HashSet<String>; 2],
    extra_keys: HashSet<String>,
}

/// Merges the staged strings into the effective target LOC files. `keep_target` strings are not written,
/// `strip` removes the listed keys from the named effective members (the port's string wins there).
fn merge_locs(
    plan: &LocPlan,
    snapshot: &Snapshot,
    keep_target: &BTreeSet<String>,
    strip: &BTreeMap<String, BTreeSet<String>>,
    progress: &Progress<'_>,
) -> Result<LocMerge> {
    let main = loc_main_paths();
    let mut members = BTreeMap::new();
    let mut keys: [HashSet<String>; 2] = [HashSet::new(), HashSet::new()];
    for (idx, (target, member)) in LOC_FILES.iter().enumerate() {
        if plan.sets[idx].is_empty() {
            bail!("no localisation rows staged for {target}");
        }
        let mut new = plan.sets[idx].clone();
        new.retain(|k, _| !keep_target.contains(k));
        let mut base = db::read_member(snapshot, Game::Ntw, member)?;
        if let Some(drop) = strip.get(&main[idx]) {
            base = strip_loc_keys(&base, drop)?;
        }
        let m = merge_loc(&base, &new).with_context(|| format!("Merge {member}"))?;
        progress(&format!(
            "{member}: {} added, {} replaced target entries",
            m.added, m.replaced
        ));
        keys[idx] = m.keys;
        members.insert((*member).to_owned(), m.bytes);
    }
    let mut extra_keys = HashSet::new();
    for (path, entries) in effective_loc_members(snapshot)? {
        if main.contains(&path) {
            continue;
        }
        match strip.get(&path) {
            Some(drop) => {
                let bytes = strip_loc_keys(&db::read_member(snapshot, Game::Ntw, &path)?, drop)?;
                extra_keys.extend(entries.into_keys().filter(|k| !drop.contains(k)));
                members.insert(path.replace('/', "\\"), bytes);
            }
            None => extra_keys.extend(entries.into_keys()),
        }
    }
    for path in strip.keys() {
        if !main.contains(path) && !members.contains_key(&path.replace('/', "\\")) {
            bail!("localisation member {path} to rewrite does not exist in the target");
        }
    }
    Ok(LocMerge {
        members,
        keys,
        extra_keys,
    })
}

fn validate_loc_coverage(
    rules: &Rules,
    tables: &BTreeMap<String, Table>,
    loc: &[HashSet<String>; 2],
    extra: &HashSet<String>,
) -> Result<()> {
    let has = |key: &str| loc.iter().any(|l| l.contains(key)) || extra.contains(key);
    let mut missing: BTreeSet<String> = BTreeSet::new();
    let mut need = |key: String| {
        if !has(&key) {
            missing.insert(key);
        }
    };
    for (key, region) in object(&rules.regions, "regions")? {
        need(format!("regions_onscreen_{key}"));
        need(format!("regions_battle_name_{key}"));
        need(format!(
            "start_pos_regions_rebel_faction_name_{key}wld_napoleon"
        ));
        if let Some(k) = region
            .get("capital_settlement_loc_key")
            .and_then(Value::as_str)
        {
            need(k.to_owned());
        }
    }
    let first = |table: &str| -> Result<Vec<String>> {
        let t = tables
            .get(table)
            .with_context(|| format!("{table} missing"))?;
        Ok(t.rows.iter().map(|r| r[0].key()).collect())
    };
    for key in first("regions_tables")? {
        need(format!("regions_onscreen_{key}"));
        need(format!("regions_battle_name_{key}"));
    }
    for key in first("campaign_map_playable_areas_tables")? {
        need(format!("campaign_map_playable_areas_onscreen_name_{key}"));
    }
    for key in first("campaign_map_towns_and_ports_tables")? {
        need(format!("campaign_map_towns_and_ports_onscreen_name_{key}"));
    }
    for key in first("campaign_map_slots_tables")? {
        need(format!("campaign_map_slots_onscreen_{key}"));
    }
    for key in first("trade_nodes_tables")? {
        need(format!("trade_nodes_display_name_{key}"));
    }
    for key in first("trade_node_groups_tables")? {
        need(format!("trade_node_groups_display_name_{key}"));
    }
    if !missing.is_empty() {
        let shown: Vec<&str> = missing.iter().take(40).map(String::as_str).collect();
        bail!(
            "{} localisation keys required by the generated database are missing:\n  {}",
            missing.len(),
            shown.join("\n  ")
        );
    }
    Ok(())
}

