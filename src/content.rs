    fn recycle_port(tables: Vec<(&str, Table)>) -> (Port, View) {
        let mut port = Port {
            tables: BTreeMap::new(),
        };
        let mut view = View::default();
        for (name, table) in tables {
            view.tables.insert(name.to_owned(), table.clone());
            port.tables.insert(
                name.to_owned(),
                PortTable::from_table(table, "seed").unwrap(),
            );
        }
        (port, view)
    }

    /// `units_to_exclusive_faction_permissions` shape: unit key, faction, allowed flag.
    fn permission_table(rows: &[(&str, &str)]) -> Table {
        let mut table = demo_table(PERMISSION_TABLE, &[]);
        table.fields = ["key", "faction", "allowed"]
            .into_iter()
            .map(|name| db::Field {
                name: name.to_owned(),
                ty: db::FieldType::StringU8,
                is_key: false,
                reference: None,
            })
            .collect();
        table.rows = rows
            .iter()
            .map(|(unit, faction)| {
                vec![
                    Cell::Str((*unit).to_owned()),
                    Cell::Str((*faction).to_owned()),
                    Cell::Str("true".to_owned()),
                ]
            })
            .collect();
        table
    }

