/// Everything that depends on how the port relates to the (possibly TSV) target.
pub struct Reconciled<'a> {
    pub port: &'a Port,
    pub loc: &'a LocPlan,
    /// Target rows (cells of the target table version) that replace dropped port rows.
    pub target_rows: &'a BTreeMap<String, Vec<Vec<Cell>>>,
    /// Port strings the target's text wins over.
    pub loc_keep_target: &'a BTreeSet<String>,
    /// Effective target LOC members (canonical path) -> keys the port's text replaces.
    pub loc_strip: &'a BTreeMap<String, BTreeSet<String>>,
}

/// Builds every pack member of the content slice from reconciled input: `db\<table>\nap_world` for each port
/// table that still has rows, the full merged `text\ui.loc` / `text\localisation.loc` and any rewritten extra
/// target LOC member. Any rule, reference or localisation inconsistency aborts with the offending items.
pub fn build_reconciled(
    snapshot: &Snapshot,
    rules: &Rules,
    input: &Reconciled<'_>,
    progress: &Progress<'_>,
) -> Result<BTreeMap<String, Vec<u8>>> {
    progress("Checking port rows against the target database");
    check_port(input.port, snapshot, rules)?;
    let view = input.port.view(input.target_rows);
    let report = rule_problems(snapshot, rules, &view)?;
    if !report.problems.is_empty() {
        let shown: Vec<&str> = report
            .problems
            .iter()
            .take(40)
            .map(String::as_str)
            .collect();
        bail!(
            "Rules do not resolve against the generated database: {} rule/database inconsistencies:\n  {}",
            report.problems.len(),
            shown.join("\n  ")
        );
    }
    let problems = recycle_problems(snapshot, rules, input.port, &view)?;
    if !problems.is_empty() {
        bail!(
            "Recycling existing factions would introduce {} faction identit(ies) or tables the target does not have:\n  {}",
            problems.len(),
            problems
                .iter()
                .take(40)
                .map(String::as_str)
                .collect::<Vec<_>>()
                .join("\n  ")
        );
    }
    progress("Checking database references");
    let refs = reference_problems(snapshot, rules, &view.tables, false)?;
    let checked = refs.checked;
    if !refs.problems.is_empty() {
        let shown: Vec<String> = refs.problems.iter().take(40).cloned().collect();
        bail!(
            "{} dangling database references:\n  {}",
            refs.problems.len(),
            shown.join("\n  ")
        );
    }
    progress("Encoding Napoleon database tables");
    let (mut members, total_rows) = encode_port(input.port, rules)?;
    let emitted_tables = members.len();

    progress("Merging localisation into the full target text files");
    let merged = merge_locs(
        input.loc,
        snapshot,
        input.loc_keep_target,
        input.loc_strip,
        progress,
    )?;
    validate_loc_coverage(rules, &view.tables, &merged.keys, &merged.extra_keys)?;
    for (name, bytes) in merged.members {
        members.insert(name, bytes);
    }
    progress(&format!(
        "Content ready: {emitted_tables} tables, {total_rows} rows, {checked} references checked"
    ));
    Ok(members)
}

