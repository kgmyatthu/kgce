/// Names (with `_tables`) of every table the conversion adds rows to: the six map tables, the curated seed tables
/// (regions and the campaign junctions) and the permission table derived from the start armies.
pub fn port_table_names() -> Vec<String> {
    MAP_TABLES
        .iter()
        .chain(SEED_TABLES.iter())
        .chain([&PERMISSION_TABLE])
        .map(|t| (*t).to_owned())
        .collect()
}

/// Tables regenerated by the map builder.
pub fn is_map_table(table: &str) -> bool {
    MAP_TABLES.contains(&table)
}

/// Port rows the converted campaign cannot do without: a target row may only be replaced by the port's row,
/// never kept instead of it (their content is tied to the generated map).
pub fn is_port_required(table: &str) -> bool {
    is_map_table(table) || table == "regions_tables"
}

