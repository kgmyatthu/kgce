/// Values of `rtab.rfield` visible in the effective target plus the generated tables; `None` when neither
/// side provides the table or field.
fn allowed_values(
    snapshot: &Snapshot,
    rules: &Rules,
    tables: &BTreeMap<String, Table>,
    rtab: &str,
    rfield: &str,
) -> Result<Option<HashSet<String>>> {
    let mut out = HashSet::new();
    let mut found = false;
    if let Some(v) = db::load_table_opt(snapshot, Game::Ntw, rules, rtab)
        .with_context(|| format!("Load referenced table {rtab}"))?
    {
        if let Ok(c) = v.column(rfield) {
            found = true;
            out.extend(v.rows.iter().map(|r| r[c].key()));
        }
    }
    if let Some(t) = tables.get(rtab) {
        if let Ok(c) = t.column(rfield) {
            found = true;
            out.extend(t.rows.iter().map(|r| r[c].key()));
        }
    }
    Ok(found.then_some(out))
}

/// Outcome of a foreign-key check.
#[derive(Clone, Debug, Default)]
pub struct RefReport {
    pub problems: Vec<String>,
    pub checked: usize,
    /// Reference fields whose target table/field is unknown and therefore could not be verified.
    pub unverified: usize,
}

/// Every foreign key of a table as `(field, referenced table with _tables, referenced field)`: the schema's
/// references with the policy references (`EXTRA_REFS`) taking precedence for the same field.
pub fn reference_edges(table: &str, fields: &[db::Field]) -> Vec<(String, String, String)> {
    let mut refs: Vec<(String, String, String)> = fields
        .iter()
        .filter_map(|f| {
            f.reference
                .as_ref()
                .map(|(rt, rf)| (f.name.clone(), db::normalize_table_name(rt), rf.clone()))
        })
        .collect();
    if let Some((_, extra)) = EXTRA_REFS.iter().find(|(n, _)| *n == table) {
        for (field, rt, rf) in extra.iter() {
            let entry = (
                (*field).to_owned(),
                db::normalize_table_name(rt),
                (*rf).to_owned(),
            );
            match refs.iter_mut().find(|e| e.0 == *field) {
                Some(existing) => *existing = entry,
                None => refs.push(entry),
            }
        }
    }
    refs
}

/// Every schema- or policy-declared foreign key of every row of `tables` must resolve in the effective target or
/// the checked tables themselves. With `skip_unresolvable` a reference into a table that is not available
/// anywhere is counted as unverified instead of dangling.
pub fn reference_problems(
    snapshot: &Snapshot,
    rules: &Rules,
    tables: &BTreeMap<String, Table>,
    skip_unresolvable: bool,
) -> Result<RefReport> {
    let mut problems: BTreeSet<String> = BTreeSet::new();
    let mut checked = 0usize;
    let mut unverified = 0usize;
    let mut cache: HashMap<(String, String), Option<HashSet<String>>> = HashMap::new();
    for (tname, t) in tables {
        let refs = reference_edges(tname, &t.fields);
        for (fname, rtab, rfield) in refs {
            let Ok(col) = t.column(&fname) else { continue };
            let used: Vec<&Cell> = t
                .rows
                .iter()
                .map(|r| &r[col])
                .filter(|c| !matches!(c, Cell::Null) && !matches!(c, Cell::Str(s) if s.is_empty()))
                .collect();
            if used.is_empty() {
                continue;
            }
            let cache_key = (rtab.clone(), rfield.clone());
            if !cache.contains_key(&cache_key) {
                let values = allowed_values(snapshot, rules, tables, &rtab, &rfield)?;
                cache.insert(cache_key.clone(), values);
            }
            let empty = HashSet::new();
            let allowed = match &cache[&cache_key] {
                Some(set) => set,
                None if skip_unresolvable => {
                    unverified += used.len();
                    continue;
                }
                None => &empty,
            };
            for c in used {
                checked += 1;
                if !allowed.contains(&c.key()) {
                    problems.insert(format!(
                        "{tname}.{fname}={:?} -> {rtab}.{rfield} missing",
                        c.key()
                    ));
                }
            }
        }
    }
    Ok(RefReport {
        problems: problems.into_iter().collect(),
        checked,
        unverified,
    })
}

/// Generated tables plus the target rows that replaced dropped port rows; `reused` holds the row identities of
/// those target rows per table.
#[derive(Clone, Debug, Default)]
pub struct View {
    pub tables: BTreeMap<String, Table>,
    pub reused: HashMap<String, HashSet<String>>,
}

/// Rule/database inconsistencies; `mapping` lists those a unit/building mapping can repair as
/// `(Mappings field, source key, message)`.
#[derive(Clone, Debug, Default)]
pub struct RuleReport {
    pub problems: Vec<String>,
    pub mapping: Vec<(&'static str, String, String)>,
}

// ---------------------------------------------------------------------------------------------
// Rules against generated tables
// ---------------------------------------------------------------------------------------------

pub fn rule_problems(snapshot: &Snapshot, rules: &Rules, view: &View) -> Result<RuleReport> {
    let tables = &view.tables;
    let reused = |table: &str, id: &str| view.reused.get(table).is_some_and(|s| s.contains(id));
    let regions = object(&rules.regions, "regions")?;
    let factions = object(&rules.factions, "factions")?;
    let units = object(&rules.units, "units")?;
    let buildings = object(&rules.buildings, "buildings")?;
    let by_slot = object(&rules.buildings_by_slot_type, "buildings_by_slot_type")?;
    let armies = object(&rules.armies, "armies")?;
    let mut problems: Vec<String> = Vec::new();
    let mut mapping: Vec<(&'static str, String, String)> = Vec::new();

    let ntw_factions_t = db::load_campaign_table(snapshot, rules, db::CampaignTable::Factions)?;
    let ntw_factions = value_set(&ntw_factions_t, ntw_factions_t.column("key")?);
    let ntw_regions_t = db::load_campaign_table(snapshot, rules, db::CampaignTable::Regions)?;
    let ntw_regions = value_set(&ntw_regions_t, ntw_regions_t.column("key")?);
    let ntw_units_t = db::load_campaign_table(snapshot, rules, db::CampaignTable::Units)?;
    let ntw_units = value_set(&ntw_units_t, 0);
    let levels_t = db::load_campaign_table(snapshot, rules, db::CampaignTable::BuildingLevels)?;
    let ntw_levels = value_set(&levels_t, 0);

    let region_t = generated(tables, "regions_tables")?;
    let region_rows = index_of(region_t, "key")?;
    let (rc, gc, bc, nc, cc) = (
        region_t.column("r")?,
        region_t.column("g")?,
        region_t.column("b")?,
        region_t.column("battle_name")?,
        region_t.column("continent")?,
    );

    // ---- factions
    let mut owned: BTreeMap<&str, usize> = BTreeMap::new();
    for (_, region) in regions {
        if let Some(owner) = region.get("owner").and_then(Value::as_str) {
            *owned.entry(owner).or_default() += 1;
        }
    }
    for (key, info) in factions {
        match info.get("source").and_then(Value::as_str) {
            Some("ntw") => {
                if !ntw_factions.contains(key) {
                    problems.push(format!(
                        "faction {key}: target faction missing from the effective factions_tables"
                    ));
                }
            }
            other => problems.push(format!(
                "faction {key}: source {other:?} is not a target faction"
            )),
        }
        match info.get("ntw_template").and_then(Value::as_str) {
            Some(t) if ntw_factions.contains(t) => {}
            other => problems.push(format!(
                "faction {key}: ntw_template {other:?} is not a faction of the target database"
            )),
        }
        if let Some(rebel) = info.get("rebel_faction").and_then(Value::as_str) {
            if !ntw_factions.contains(rebel) {
                problems.push(format!(
                    "faction {key}: rebel_faction {rebel} is not a known faction"
                ));
            }
        }
        let held = owned.get(key.as_str()).copied().unwrap_or(0);
        if info.get("regions").and_then(Value::as_u64) != Some(held as u64) {
            problems.push(format!(
                "faction {key}: rules region count {} does not match the {held} regions it owns",
                info.get("regions").unwrap_or(&Value::Null)
            ));
        }
        if info.get("alive").and_then(Value::as_bool) != Some(held > 0) {
            problems.push(format!(
                "faction {key}: alive flag disagrees with {held} owned regions"
            ));
        }
        if let Some(cap) = info.get("capital").and_then(Value::as_str) {
            if regions
                .get(cap)
                .and_then(|r| r.get("owner"))
                .and_then(Value::as_str)
                != Some(key.as_str())
            {
                problems.push(format!(
                    "faction {key}: capital {cap} is not one of its regions"
                ));
            }
        } else if held > 0 {
            problems.push(format!(
                "faction {key}: owns {held} regions but has no capital"
            ));
        }
    }

    // ---- regions
    let mut colours: HashMap<(String, [i64; 3]), &str> = HashMap::new();
    for (key, region) in regions {
        let Some(&row) = region_rows.get(key) else {
            problems.push(format!("region {key}: no generated regions_tables row"));
            continue;
        };
        if ntw_regions.contains(key) && !reused("regions_tables", key) {
            problems.push(format!("region {key}: collides with a target region"));
        }
        let row = &region_t.rows[row];
        match region.get("owner").and_then(Value::as_str) {
            Some(o) if factions.contains_key(o) => {}
            other => problems.push(format!(
                "region {key}: owner {other:?} is not a faction of the rules"
            )),
        }
        match region.get("rebel_faction").and_then(Value::as_str) {
            Some(r) if ntw_factions.contains(r) => {}
            other => problems.push(format!(
                "region {key}: rebel_faction {other:?} is not a known faction"
            )),
        }
        if region.get("continent").and_then(Value::as_str) != row[cc].as_str() {
            problems.push(format!(
                "region {key}: continent differs between rules and database rows"
            ));
        }
        if region
            .get("capital_settlement_name")
            .and_then(Value::as_str)
            != row[nc].as_str()
        {
            problems.push(format!(
                "region {key}: capital name differs between rules and database rows"
            ));
        }
        match region
            .get("lookup_rgb")
            .and_then(Value::as_array)
            .map(|a| a.iter().map(Value::as_i64).collect::<Vec<_>>())
        {
            Some(rgb) if rgb.len() == 3 && rgb.iter().all(Option::is_some) => {
                let rgb = [
                    rgb[0].unwrap_or(-1),
                    rgb[1].unwrap_or(-1),
                    rgb[2].unwrap_or(-1),
                ];
                let have = [&row[rc], &row[gc], &row[bc]].map(Cell::key);
                let want = rgb.map(|v| v.to_string());
                if have != want {
                    problems.push(format!(
                        "region {key}: lookup colour {want:?} differs from database row {have:?}"
                    ));
                }
                let theatre = region
                    .get("theatre")
                    .map(|t| t.to_string())
                    .unwrap_or_default();
                if let Some(other) = colours.insert((theatre, rgb), key.as_str()) {
                    problems.push(format!(
                        "regions {key} and {other} share lookup colour {rgb:?} inside one theatre"
                    ));
                }
            }
            _ => problems.push(format!("region {key}: lookup_rgb must be three integers")),
        }
    }
    for k in region_rows.keys() {
        if regions.contains_key(k) {
            continue;
        }
        if ntw_regions.contains(k) && !reused("regions_tables", k) {
            problems.push(format!(
                "regions_tables row {k} collides with a target region"
            ));
        }
    }

    // ---- units, buildings, armies
    for (etw, ntw) in units {
        match ntw {
            Value::Null => {}
            Value::String(s) if ntw_units.contains(s) => {}
            other => {
                let message =
                    format!("unit mapping {etw}: {other} is not a unit of the target database");
                problems.push(message.clone());
                if let Value::String(stand_in) = other {
                    mapping.push(("units", stand_in.clone(), message));
                }
            }
        }
    }
    for (etw, ntw) in buildings {
        match ntw {
            Value::Null => {}
            Value::String(s) if ntw_levels.contains(s) => {}
            other => {
                let message = format!(
                    "building mapping {etw}: {other} is not a building level of the target database"
                );
                problems.push(message.clone());
                mapping.push(("buildings", etw.clone(), message));
            }
        }
    }
    for (chain, slots) in by_slot {
        let slots = slots.as_object();
        match slots {
            Some(slots) => {
                for (slot, level) in slots {
                    if !level.as_str().is_some_and(|l| ntw_levels.contains(l)) {
                        problems.push(format!("building slot mapping {chain}.{slot}: {level} is not a building level of the target database"));
                    }
                }
            }
            None => problems.push(format!("building slot mapping {chain} must be an object")),
        }
    }
    for (faction, list) in armies {
        if !factions.contains_key(faction) {
            problems.push(format!("armies: {faction} is not a faction of the rules"));
        }
        for army in list.as_array().into_iter().flatten() {
            match army.get("region").and_then(Value::as_str) {
                Some(r) if regions.contains_key(r) => {}
                other => {
                    problems.push(format!("armies.{faction}: region {other:?} does not exist"))
                }
            }
            for unit in army
                .get("units")
                .and_then(Value::as_array)
                .into_iter()
                .flatten()
            {
                if !unit.as_str().is_some_and(|u| ntw_units.contains(u)) {
                    let message =
                        format!("armies.{faction}: {unit} is not a unit of the target database");
                    problems.push(message.clone());
                    if let Some(u) = unit.as_str() {
                        mapping.push(("units", u.to_owned(), message));
                    }
                }
            }
        }
    }
    Ok(RuleReport { problems, mapping })
}

/// The world campaign recycles existing factions only: every faction identity used by the generated content must
/// already exist in the effective target database, and the port may only carry the tables of
/// [`port_table_names`]. Returns the violations.
pub fn recycle_problems(
    snapshot: &Snapshot,
    rules: &Rules,
    port: &Port,
    view: &View,
) -> Result<Vec<String>> {
    let target_t = db::load_campaign_table(snapshot, rules, db::CampaignTable::Factions)?;
    let target = value_set(&target_t, target_t.column("key")?);
    recycle_problems_in(&target, rules, port, view)
}

/// [`recycle_problems`] against an explicit set of target faction keys.
fn recycle_problems_in(
    target: &HashSet<String>,
    rules: &Rules,
    port: &Port,
    view: &View,
) -> Result<Vec<String>> {
    let mut problems = Vec::new();
    let allowed = port_table_names();
    let surplus: BTreeSet<&String> = port
        .tables
        .keys()
        .chain(view.tables.keys())
        .filter(|name| !allowed.contains(*name))
        .collect();
    for name in surplus {
        problems.push(format!(
            "{name} would be generated although only {allowed:?} may be"
        ));
    }
    for (key, info) in object(&rules.factions, "factions")? {
        if info.get("source").and_then(Value::as_str) != Some("ntw") {
            problems.push(format!(
                "faction {key} is not a target faction (source is not ntw)"
            ));
        }
        if !target.contains(key) {
            problems.push(format!(
                "faction {key} is not defined by the target factions table"
            ));
        }
    }
    for (key, region) in object(&rules.regions, "regions")? {
        for field in ["owner", "rebel_faction"] {
            match region.get(field).and_then(Value::as_str) {
                Some(f) if target.contains(f) => {}
                other => problems.push(format!(
                    "region {key}: {field} {other:?} is not a faction of the target database"
                )),
            }
        }
    }
    for faction in object(&rules.armies, "armies")?.keys() {
        if !target.contains(faction) {
            problems.push(format!(
                "armies: {faction} is not a faction of the target database"
            ));
        }
    }
    if let Some(t) = view.tables.get(PERMISSION_TABLE) {
        let c = t.column("faction")?;
        let unknown: BTreeSet<String> = t
            .rows
            .iter()
            .map(|r| r[c].key())
            .filter(|f| !target.contains(f))
            .collect();
        if !unknown.is_empty() {
            problems.push(format!(
                "{PERMISSION_TABLE}.faction would refer to faction(s) the target does not define: {}",
                unknown.into_iter().take(8).collect::<Vec<_>>().join(", ")
            ));
        }
    }
    Ok(problems)
}

